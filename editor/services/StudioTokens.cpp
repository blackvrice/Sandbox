const StudioColors& studioColors(StudioTheme theme) noexcept {
    switch (theme) {
    case StudioTheme::Light:
        return kLight;
    case StudioTheme::HighContrast:
        return kHighContrast;
    case StudioTheme::Dark:
        break;
    }
    return kDark;
}

